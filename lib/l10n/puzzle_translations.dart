  /// Look up the localized [field] (`title` / `description` / `hint`) for
  /// [puzzleId] in [languageCode]. Returns null if no translation exists; the
  /// caller should fall back to the English value on [Puzzle].
  static String? translate({
    required String puzzleId,
    required String field,
    required String languageCode,
  }) {
    return _translations[languageCode]?[puzzleId]?[field];
  }
}

/// Convenience accessors so screens can write `puzzle.localizedTitle(context)`
/// instead of threading locale + field name everywhere.
extension PuzzleLocalized on Puzzle {
  String localizedTitle(BuildContext context) {
    final code = Localizations.localeOf(context).languageCode;
    return PuzzleI18n.translate(
          puzzleId: id,
          field: 'title',
          languageCode: code,
        ) ??
        title;
  }

  String localizedDescription(BuildContext context) {
    final code = Localizations.localeOf(context).languageCode;
    return PuzzleI18n.translate(
          puzzleId: id,
          field: 'description',
          languageCode: code,
        ) ??
        description;
  }

  /// Returns a localized hint for this puzzle.
  ///
  /// Lookup order:
  ///   1. Curated translation in `PuzzleI18n` (matches the puzzle ID + locale).
  ///   2. The English `hint` field on the [Puzzle] itself.
  ///   3. **Derived fallback** — if the puzzle has a [solutionTree] with at
  ///      least one correct first-move branch, return a generic
  ///      "Look at row N, column X — there's a strong move here." pointing
  ///      at the first valid first move. This keeps the hint dialog useful
  ///      for OGS puzzles where the OGS author left the move-tree text empty.
  ///   4. Final fallback: a generic "look for atari / weak groups" hint.
  String localizedHint(BuildContext context) {
    final code = Localizations.localeOf(context).languageCode;
    final translated = PuzzleI18n.translate(
      puzzleId: id,
      field: 'hint',
      languageCode: code,
    );
    if (translated != null && translated.trim().isNotEmpty) return translated;
    if (hint.trim().isNotEmpty) return hint;

    final l = AppLocalizations.of(context);
    final firstMoves = solutionTree?.children ?? const [];
    if (firstMoves.isNotEmpty) {
      final m = firstMoves.first;
      // Convert col index to Go-style letter (A-T, skipping I). Display rows
      // 1..N from the top so beginners see human-readable coordinates rather
      // than the engine's 0-indexed values.
      const letters = 'ABCDEFGHJKLMNOPQRST';
      final colLetter = (m.col >= 0 && m.col < letters.length)
          ? letters[m.col]
          : '?';
      return l.hintLookAt(m.row + 1, colLetter);
    }
    return l.hintFallbackGeneric;
  }

  String localizedExplanation(BuildContext context) {
    final code = Localizations.localeOf(context).languageCode;
    return PuzzleI18n.translate(
          puzzleId: id,
          field: 'explanation',
          languageCode: code,
        ) ??
        explanation;
  }
